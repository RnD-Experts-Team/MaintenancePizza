<?php

namespace App\Enums;

/**
 * A trip is open while the technician can still use its link, and closed
 * once the office closes it (the link then stops working).
 */
enum TripStatus: string
{
    case Open = 'open';
    case Closed = 'closed';

    public function label(): string
    {
        return match ($this) {
            self::Open => 'Open',
            self::Closed => 'Closed',
        };
    }

    /**
     * @return array<int, string>
     */
    public static function values(): array
    {
        return array_map(fn (self $c) => $c->value, self::cases());
    }
}
